OUTPUT_DIR = "public/voice-audio"
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Load existing farmer_prompts.json and update
json_path = "farmer_prompts.json"
existing_prompts = {}
if os.path.exists(json_path):
    with open(json_path, "r", encoding="utf-8") as f:
        existing_prompts = json.load(f)

existing_prompts.update(AUTH_PROMPTS)

with open(json_path, "w", encoding="utf-8") as f:
    json.dump(existing_prompts, f, ensure_ascii=False, indent=2)

print(f"Updated farmer_prompts.json with {len(AUTH_PROMPTS)} auth prompts.")

# Target languages
LANGS = ["hi", "en", "te", "ta", "pa", "mr", "kn", "bn", "gu"]

success = 0
for key, lang_map in AUTH_PROMPTS.items():
    safe_key = key.replace(".", "_")
    for lang in LANGS:
        text = lang_map.get(lang)
        if not text:
            continue
        filename = f"{safe_key}_{lang}.mp3"
        filepath = os.path.join(OUTPUT_DIR, filename)

        if os.path.exists(filepath) and os.path.getsize(filepath) > 0:
            success += 1
            continue

        try:
            print(f"Generating {filename} ({lang})...")
            tts = gTTS(text=text, lang=lang, slow=False)
            tts.save(filepath)
            success += 1
            time.sleep(0.25)
        except Exception as e:
            print(f"Error {filename}: {e}")

print(f"Auth voice packs generation complete! Verified: {success} files.")
