OUTPUT_DIR = "public/voice-audio"
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Save updated JSON
with open("farmer_prompts.json", "w", encoding="utf-8") as f:
    json.dump(PROMPTS, f, ensure_ascii=False, indent=2)

print(f"Saved {len(PROMPTS)} prompt definitions in farmer_prompts.json")

# Target languages to ensure 100% audio coverage
LANGS = ["hi", "en", "te", "ta", "pa", "mr", "kn", "bn", "gu"]

success_count = 0
for key, lang_map in PROMPTS.items():
    safe_key = key.replace(".", "_")
    for lang in LANGS:
        text = lang_map.get(lang)
        if not text:
            continue
        
        filename = f"{safe_key}_{lang}.mp3"
        filepath = os.path.join(OUTPUT_DIR, filename)
        
        # Check if already exists
        if os.path.exists(filepath) and os.path.getsize(filepath) > 0:
            success_count += 1
            continue
        
        try:
            print(f"Generating: {filename} ({lang})...")
            tts = gTTS(text=text, lang=lang, slow=False)
            tts.save(filepath)
            success_count += 1
            time.sleep(0.3)
        except Exception as e:
            print(f"Error for {filename}: {e}")

print(f"Finished. Total verified audio files: {success_count}")
